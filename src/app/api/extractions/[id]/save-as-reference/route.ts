import { NextResponse } from "next/server";
import { auth } from "@/lib/auth";
import { prisma } from "@/lib/prisma";
import { generateReferenceText, inferProjectType } from "@/lib/reference-generator";

const MAX_REFERENCES = 20;

export async function POST(
  req: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const session = await auth();
    if (!session?.user?.id) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const { id } = await params;

    const extraction = await prisma.extraction.findUnique({
      where: { id },
      select: {
        id: true,
        userId: true,
        name: true,
        finalized: true,
        items: true,
        // Pull linked measurements so the reference generator can flag
        // estimator-traced items with [VERIFIED BY MANUAL TRACE]. Only
        // measurements with an itemId are useful — unlinked traces are
        // exploratory marks the estimator made but didn't tie to a takeoff
        // line, so they're excluded.
        measurements: { where: { itemId: { not: null } } },
      },
    });

    if (!extraction || extraction.userId !== session.user.id) {
      return NextResponse.json({ error: "Not found" }, { status: 404 });
    }

    if (!extraction.finalized) {
      return NextResponse.json(
        { error: "Extraction must be finalized before saving as reference" },
        { status: 400 }
      );
    }

    // Check if already saved as reference
    const existingRef = await prisma.referenceExample.findFirst({
      where: { sourceExtractionId: id, userId: session.user.id },
    });
    if (existingRef) {
      return NextResponse.json(
        { error: "This extraction has already been saved as a reference example" },
        { status: 400 }
      );
    }

    // Check reference limit
    const refCount = await prisma.referenceExample.count({
      where: { userId: session.user.id },
    });
    if (refCount >= MAX_REFERENCES) {
      return NextResponse.json(
        {
          error: `Maximum ${MAX_REFERENCES} reference examples reached. Deactivate or delete an existing one first.`,
        },
        { status: 400 }
      );
    }

    // Parse optional overrides from request body
    const body = await req.json().catch(() => ({}));
    const customName = body.name as string | undefined;
    const customProjectType = body.projectType as string | undefined;

    // Generate reference text from corrected items + linked traces
    const referenceText = generateReferenceText(
      extraction.items,
      extraction.name,
      extraction.measurements
    );
    if (!referenceText) {
      return NextResponse.json(
        { error: "No valid items to generate reference from" },
        { status: 400 }
      );
    }

    const projectType = customProjectType || inferProjectType(extraction.items);

    const reference = await prisma.referenceExample.create({
      data: {
        name: customName || `${extraction.name} (auto-generated)`,
        projectType,
        rawText: referenceText,
        isActive: true,
        userId: session.user.id,
        sourceExtractionId: id,
        isAutoGenerated: true,
      },
    });

    console.log(
      `[learning] Saved extraction "${extraction.name}" as reference example ` +
        `(${extraction.items.length} items, ${referenceText.length} chars)`
    );

    return NextResponse.json({
      success: true,
      referenceId: reference.id,
      itemCount: extraction.items.length,
      textLength: referenceText.length,
    });
  } catch (error) {
    console.error("Save-as-reference error:", error);
    return NextResponse.json(
      {
        error: error instanceof Error
          ? error.message
          : "Failed to save as reference",
      },
      { status: 500 }
    );
  }
}
